/**
 * 魔法阵文字环用的矢量描边字体：纯数据，不含逻辑、不涉及渲染。
 *
 * 为什么不直接用系统字体：项目里不能 vendor 字体文件（中文字体几 MB 起、且是二进制），
 * 而 canvas 的 fillText 各端字形不同 —— 那会让同一份参数在不同设备上出不同的图。
 * 手写一套描边字形则完全落在纯逻辑层：跨端逐像素一致、可写测试，而且**描边风格和符文带
 * 是同一套视觉语言**（细线刻痕），系统字体放进魔法阵反而突兀。
 *
 * 坐标系：每格 0..12 是字高（0 = 顶，12 = 基线），x 向右。所以 y 是**向下**的，
 * 排版时换成「向外」要把 y 翻过来。
 *
 * 字形用整数网格（多数取半格）是为了**数据可读、写错一眼能看出来** —— 和符文那套
 * 吸附到 0.1 网格是同一个理由。整张字体表可以渲染成一张样张直接看，改完务必看一眼。
 *
 * 只有大写：这类铭文本来就是大写的，所以输入统一转大写（`normalizeText`）。
 */

