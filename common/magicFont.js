/**
 * 归一化输入：转大写、去掉字体里没有的字符替换成空格之外的保留。
 * 字体只收大写，所以这一步是必须的 —— 否则小写输入一个字都排不出来。
 */
export function normalizeText(text) {
	return String(text === undefined || text === null ? '' : text).toUpperCase()
}

/** 取一个字形的副本（避免调用方改到共享的字形表）。 */
export function glyphFor(char) {
	return MAGIC_FONT[char] || null
}
